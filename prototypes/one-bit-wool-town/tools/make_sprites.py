def render(name: str, rows: Sprite) -> Image.Image:
    width, height = CANVAS_SIZES[name]
    if len(rows) != height or any(len(row) != width for row in rows):
        raise ValueError(f"{name} must remain {width}x{height}")
    if any(set(row) - {".", "#"} for row in rows):
        raise ValueError(f"{name} contains a non-pixel character")

    image = Image.new("RGBA", (width, height), TRANSPARENT)
    pixels = image.load()
    for y, row in enumerate(rows):
        for x, cell in enumerate(row):
            if cell == "#":
                pixels[x, y] = INK
    return image


def make_contact_sheet(images: dict[str, Image.Image]) -> None:
    scale = 8
    columns = 5
    gutter = 16
    max_width = max(width for width, _ in CANVAS_SIZES.values())
    max_height = max(height for _, height in CANVAS_SIZES.values())
    cell_width = max_width * scale + gutter * 2
    cell_height = max_height * scale + gutter * 2
    row_count = (len(images) + columns - 1) // columns
    sheet = Image.new(
        "RGBA",
        (columns * cell_width, row_count * cell_height),
        PAPER,
    )

    for index, image in enumerate(images.values()):
        enlarged = image.resize(
            (image.width * scale, image.height * scale),
            Image.Resampling.NEAREST,
        )
        x = (index % columns) * cell_width + gutter
        x += (max_width - image.width) * scale // 2
        y = (index // columns) * cell_height + gutter
        y += (max_height - image.height) * scale
        sheet.alpha_composite(enlarged, (x, y))

    sheet.save(CONTACT_SHEET)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    images = {name: render(name, rows) for name, rows in SPRITES.items()}
    for name, image in images.items():
        image.save(OUT / name)
    make_contact_sheet(images)
    print(f"wrote {len(images)} sprites + contact sheet")


if __name__ == "__main__":
    main()
